package com.veil.module.modules.world;

import com.veil.Veil;
import com.veil.event.EventHandler;
import com.veil.event.events.RenderWorldEvent;
import com.veil.event.events.TickEvent;
import com.veil.module.Category;
import com.veil.module.Module;
import com.veil.setting.BoolSetting;
import com.veil.setting.IntSetting;
import net.minecraft.gizmos.GizmoStyle;
import net.minecraft.gizmos.Gizmos;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.LevelChunk;
import net.minecraft.world.level.chunk.LevelChunkSection;
import net.minecraft.world.level.chunk.status.ChunkStatus;
import net.minecraft.world.phys.AABB;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Old Chunks: squares on the ground over chunks that were first generated by an old version of the
 * game. Old chunks are where somebody travelled long ago, so a line of them leads along an old trail
 * towards old bases.
 *
 * <p>Overworld: chunks made before 1.18 still carry the old bedrock floor at y 0–4, where new chunks
 * only have bedrock at the very bottom of the world. Nether: chunks made before 1.16 hold none of the
 * 1.16 blocks (basalt, blackstone, crimson and warped nylium and stems, soul soil, ancient debris,
 * nether gold ore). The End has no reliable marker and is not judged.
 */
public final class OldChunks extends Module {

    private enum Age { OLD, NEW, UNKNOWN }

    private static final int OLD_COLOUR = 0xFFFF3B3B;
    private static final int NEW_COLOUR = 0xFF3BFF7A;

    private final BoolSetting showOld = register(new BoolSetting("Show Old", true));
    private final BoolSetting showNew = register(new BoolSetting("Show New", false));
    private final IntSetting  height  = register(new IntSetting("Draw Height", 0, -64, 64));

    private final Map<Long, Age> ages = new HashMap<>();
    private final List<Long> queue = new ArrayList<>();
    private int queueIndex, oldCount;

    public OldChunks() {
        super("OldChunks",
              "Squares chunks generated in old versions of the game — old chunks mark old trails and old bases.",
              Category.WORLD);
    }

    @Override
    public void onEnable() {
        ages.clear();
        queue.clear();
        queueIndex = 0;
        oldCount = 0;
    }

    @EventHandler
    private void onTick(TickEvent.Pre event) {
        if (!Veil.inGame()) return;

        if (queueIndex >= queue.size()) {
            queue.clear();
            queueIndex = 0;
            int r = Math.max(2, Veil.mc.options.getEffectiveRenderDistance());
            ChunkPos centre = Veil.mc.player.chunkPosition();
            for (int dx = -r; dx <= r; dx++) {
                for (int dz = -r; dz <= r; dz++) queue.add(ChunkPos.pack(centre.x() + dx, centre.z() + dz));
            }
            Set<Long> inRange = new HashSet<>(queue);
            ages.keySet().removeIf(key -> !inRange.contains(key));
            int n = 0;
            for (Age age : ages.values()) if (age == Age.OLD) n++;
            oldCount = n;
        }

        for (int n = 0; n < 40 && queueIndex < queue.size(); n++) {
            long key = queue.get(queueIndex++);
            Age age = ages.get(key);
            if (age == null || age == Age.UNKNOWN) ages.put(key, judge(key));
        }
    }

    private Age judge(long key) {
        LevelChunk chunk = Veil.mc.level.getChunkSource()
                .getChunk(ChunkPos.getX(key), ChunkPos.getZ(key), ChunkStatus.FULL, false);
        if (chunk == null) return Age.UNKNOWN;

        LevelChunkSection[] sections = chunk.getSections();
        if (Veil.mc.level.dimension() == Level.OVERWORLD) {
            // The section holding y 0–15: old chunks keep their old bedrock floor there.
            int index = chunk.getSectionIndex(0);
            if (index < 0 || index >= sections.length) return Age.UNKNOWN;
            LevelChunkSection section = sections[index];
            if (section == null || section.hasOnlyAir()) return Age.UNKNOWN;
            if (!section.maybeHas(state -> state.is(Blocks.BEDROCK))) return Age.NEW;
            for (int y = 0; y < 5; y++) {
                for (int z = 0; z < 16; z++) {
                    for (int x = 0; x < 16; x++) {
                        if (section.getBlockState(x, y, z).is(Blocks.BEDROCK)) return Age.OLD;
                    }
                }
            }
            return Age.NEW;
        }

        if (Veil.mc.level.dimension() == Level.NETHER) {
            boolean any = false;
            for (LevelChunkSection section : sections) {
                if (section == null || section.hasOnlyAir()) continue;
                any = true;
                if (section.maybeHas(OldChunks::isNewNetherBlock)) {
                    // maybeHas can be a false alarm on mixed palettes, so confirm it.
                    for (int y = 0; y < 16; y++) {
                        for (int z = 0; z < 16; z++) {
                            for (int x = 0; x < 16; x++) {
                                if (isNewNetherBlock(section.getBlockState(x, y, z))) return Age.NEW;
                            }
                        }
                    }
                }
            }
            return any ? Age.OLD : Age.UNKNOWN;
        }

        return Age.UNKNOWN;
    }

    private static boolean isNewNetherBlock(BlockState state) {
        return state.is(Blocks.BASALT) || state.is(Blocks.BLACKSTONE) || state.is(Blocks.CRIMSON_NYLIUM)
                || state.is(Blocks.WARPED_NYLIUM) || state.is(Blocks.SOUL_SOIL) || state.is(Blocks.CRIMSON_STEM)
                || state.is(Blocks.WARPED_STEM) || state.is(Blocks.ANCIENT_DEBRIS) || state.is(Blocks.NETHER_GOLD_ORE);
    }

    @EventHandler
    private void onRender(RenderWorldEvent event) {
        if (!Veil.inGame() || ages.isEmpty()) return;

        double y = Math.floor(Veil.mc.player.getY()) - height.get();
        for (Map.Entry<Long, Age> e : ages.entrySet()) {
            Age age = e.getValue();
            int colour;
            if (age == Age.OLD && showOld.get()) colour = OLD_COLOUR;
            else if (age == Age.NEW && showNew.get()) colour = NEW_COLOUR;
            else continue;

            int x = ChunkPos.getX(e.getKey()) << 4;
            int z = ChunkPos.getZ(e.getKey()) << 4;
            AABB box = new AABB(x, y, z, x + 16, y + 0.05, z + 16);
            int fill = age == Age.OLD ? 0x45 : 0x20;
            Gizmos.cuboid(box, GizmoStyle.strokeAndFill(colour, 1f, (fill << 24) | (colour & 0xFFFFFF)));
        }
    }

    @Override
    public String suffix() {
        return oldCount > 0 ? String.valueOf(oldCount) : null;
    }
}
